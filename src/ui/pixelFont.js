// uses it for all text.
//
// Each glyph is 5 pixels wide. '#' is a filled pixel and '.' is empty.
// Rows are separated by spaces, top to bottom:
//   - 7 rows for most glyphs (capital letters fill all 7).
//   - 9 rows for glyphs that hang below the line (g, j, p, q, y, and , ;).
//
// The font covers the printable ASCII characters only (space to ~). Text
// with other characters, such as curly quotes or long dashes, will not
// draw them - tests/font.test.js checks the case text for this.

