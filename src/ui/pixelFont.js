const EMPTY_ROW = '.'.repeat(GLYPH_WIDTH);

// Every glyph as { char, rows }, where rows is always GLYPH_HEIGHT strings
// (short glyphs are padded with empty rows at the bottom).
export const GLYPHS = GLYPH_DATA.map(([char, data]) => {
  const rows = data.split(' ');
  while (rows.length < GLYPH_HEIGHT) rows.push(EMPTY_ROW);
  return { char, rows };
});

// All the characters the font can draw, in texture order.
export const FONT_CHARS = GLYPHS.map((glyph) => glyph.char).join('');

// Returns the characters in a string that the font cannot draw.
// Line breaks are fine: they start a new line.
export function unsupportedCharacters(text) {
  return [...new Set(text)].filter(
    (char) => char !== '\n' && !FONT_CHARS.includes(char)
  );
}
